def render_footer(fmt: str = "text") -> str:
    if fmt == "text":
        return f"\n{'-' * 80}\n{DISCLAIMER_SHORT}"
    elif fmt == "markdown":
        return f"---\n> *{DISCLAIMER_SHORT}*"
    elif fmt == "html":
        return f"<footer class=\"ra-disclaimer\"><p>{DISCLAIMER_SHORT}</p></footer>"
    else:
        raise ValueError(f"Unknown format: {fmt}")